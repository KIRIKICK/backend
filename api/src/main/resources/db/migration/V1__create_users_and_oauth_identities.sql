create table users (
    id bigint generated by default as identity primary key,
    uuid uuid not null,
    display_name text not null,
    profile_image_url text,
    birth_year integer,
    status varchar(20) not null,
    withdrawn_at timestamp with time zone,
    created_at timestamp with time zone not null,
    updated_at timestamp with time zone not null,
    constraint uk_users_uuid unique (uuid),
    constraint ck_users_status check (status in ('ACTIVE', 'WITHDRAWN', 'SUSPENDED', 'BANNED'))
);

create table oauth_identities (
    id bigint generated by default as identity primary key,
    user_id bigint not null,
    provider varchar(20) not null,
    provider_subject varchar(255) not null,
    created_at timestamp with time zone not null,
    constraint fk_oauth_identities_user foreign key (user_id) references users (id) on delete restrict,
    constraint uk_oauth_identities_provider_subject unique (provider, provider_subject),
    constraint uk_oauth_identities_user_provider unique (user_id, provider),
    constraint ck_oauth_identities_provider check (provider in ('KAKAO', 'APPLE'))
);
