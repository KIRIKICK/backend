create table reward_presets (
    id bigint generated by default as identity primary key,
    title text not null,
    description text not null
);

create table question_presets (
    id bigint generated by default as identity primary key,
    question_text text not null
);

create table question_preset_choices (
    id bigint generated by default as identity primary key,
    question_preset_id bigint not null,
    choice_text text not null,
    constraint fk_question_preset_choices_question
        foreign key (question_preset_id) references question_presets (id)
        on delete no action not deferrable
);

create table rooms (
    id bigint generated by default as identity primary key,
    host_user_id bigint not null,
    selected_reward_preset_id bigint not null,
    status varchar(20) not null,
    result_state varchar(20) not null default 'NOT_READY',
    opened_at timestamptz(6),
    closes_at timestamptz(6),
    created_at timestamptz(6) not null,
    constraint fk_rooms_host_user
        foreign key (host_user_id) references users (id) on delete no action not deferrable,
    constraint fk_rooms_selected_reward_preset
        foreign key (selected_reward_preset_id) references reward_presets (id)
        on delete no action not deferrable,
    constraint ck_rooms_status check (status in ('OPEN', 'CLOSED')),
    constraint ck_rooms_result_state check (result_state in ('NOT_READY', 'FINAL')),
    constraint ck_rooms_publication_times check ((opened_at is null) = (closes_at is null)),
    constraint ck_rooms_closes_after_open check (closes_at > opened_at)
);

create unique index uk_rooms_open_per_host on rooms (host_user_id) where status = 'OPEN';

create table games (
    id bigint generated by default as identity primary key,
    room_id bigint not null,
    question_preset_id bigint not null,
    question_text_snapshot text not null,
    correct_choice_id bigint,
    created_at timestamptz(6) not null,
    constraint fk_games_room
        foreign key (room_id) references rooms (id) on delete no action not deferrable,
    constraint fk_games_question_preset
        foreign key (question_preset_id) references question_presets (id)
        on delete no action not deferrable,
    constraint uk_games_room_question unique (room_id, question_preset_id)
);

create table choices (
    id bigint generated by default as identity primary key,
    game_id bigint not null,
    position integer not null,
    text_snapshot text not null,
    constraint fk_choices_game
        foreign key (game_id) references games (id) on delete no action not deferrable,
    constraint uk_choices_game_id unique (game_id, id),
    constraint uk_choices_game_position unique (game_id, position)
);

alter table games add constraint fk_games_correct_choice
    foreign key (id, correct_choice_id) references choices (game_id, id)
    match simple on delete no action not deferrable;
