create table rooms (
    id bigint generated by default as identity primary key,
    uuid uuid not null,
    owner_id bigint not null,
    name text not null,
    created_at timestamp with time zone not null,
    updated_at timestamp with time zone not null,
    constraint uk_rooms_uuid unique (uuid),
    constraint fk_rooms_owner foreign key (owner_id) references users (id) on delete restrict,
    constraint ck_rooms_name check (name ~ '[^[:space:]]')
);
create index idx_rooms_owner on rooms (owner_id);

create table games (
    id bigint generated by default as identity primary key,
    uuid uuid not null,
    room_id bigint not null,
    creator_id bigint not null,
    type varchar(20) not null,
    status varchar(20) not null,
    expires_at timestamp with time zone not null,
    created_at timestamp with time zone not null,
    updated_at timestamp with time zone not null,
    constraint uk_games_uuid unique (uuid),
    constraint fk_games_room foreign key (room_id) references rooms (id) on delete restrict,
    constraint fk_games_creator foreign key (creator_id) references users (id) on delete restrict,
    constraint ck_games_type check (type in ('NAZAL', 'VOTE')),
    constraint ck_games_status check (status in ('IN_PROGRESS', 'FINALIZING', 'FINISHED'))
);
create index idx_games_room on games (room_id);
create index idx_games_creator on games (creator_id);

create table game_participants (
    id bigint generated by default as identity primary key,
    uuid uuid not null,
    game_id bigint not null,
    user_id bigint not null,
    started_at timestamp with time zone,
    created_at timestamp with time zone not null,
    updated_at timestamp with time zone not null,
    constraint uk_game_participants_uuid unique (uuid),
    constraint uk_game_participants_game_user unique (game_id, user_id),
    constraint uk_game_participants_game_id unique (game_id, id),
    constraint fk_game_participants_game foreign key (game_id) references games (id) on delete restrict,
    constraint fk_game_participants_user foreign key (user_id) references users (id) on delete restrict
);
create index idx_game_participants_user on game_participants (user_id);

create table game_answers (
    id bigint generated by default as identity primary key,
    uuid uuid not null,
    game_id bigint not null,
    participant_id bigint not null,
    selected_option_key varchar(1),
    target_participant_id bigint,
    accepted_at timestamp with time zone not null,
    created_at timestamp with time zone not null,
    constraint uk_game_answers_uuid unique (uuid),
    constraint uk_game_answers_participant unique (participant_id),
    constraint fk_game_answers_participant foreign key (game_id, participant_id)
        references game_participants (game_id, id) on delete restrict,
    constraint fk_game_answers_target foreign key (game_id, target_participant_id)
        references game_participants (game_id, id) on delete restrict,
    constraint ck_game_answers_payload check (
        (selected_option_key is not null and selected_option_key in ('1', '2', '3', '4') and target_participant_id is null)
        or (selected_option_key is null and target_participant_id is not null)
    ),
    constraint ck_game_answers_not_self_vote check (target_participant_id is null or target_participant_id <> participant_id)
);
create index idx_game_answers_game on game_answers (game_id);
create index idx_game_answers_target on game_answers (game_id, target_participant_id);
