-- N1 has no deletion workflow; all five FKs reject referenced deletes rather than cascade.
create table reward_presets (
    id bigint generated by default as identity primary key,
    title text not null,
    description text not null
);

create table rooms (
    id bigint generated by default as identity primary key,
    host_user_id bigint not null,
    selected_reward_preset_id bigint not null,
    created_at timestamp with time zone not null,
    opened_at timestamp with time zone,
    confirmed_early_end_at timestamp with time zone,
    constraint fk_rooms_host_user
        foreign key (host_user_id) references users (id) on delete no action,
    constraint fk_rooms_selected_reward_preset
        foreign key (selected_reward_preset_id) references reward_presets (id) on delete no action
);

create table games (
    id bigint generated by default as identity primary key,
    room_id bigint not null,
    ordinal integer not null,
    question_text_snapshot text not null,
    correct_choice_id bigint,
    created_at timestamp with time zone not null,
    constraint fk_games_room foreign key (room_id) references rooms (id) on delete no action
);

create table choices (
    id bigint generated by default as identity primary key,
    game_id bigint not null,
    position integer not null,
    text_snapshot text not null,
    constraint fk_choices_game foreign key (game_id) references games (id) on delete no action
);

alter table games
    add constraint fk_games_correct_choice
    foreign key (correct_choice_id) references choices (id) on delete no action;

